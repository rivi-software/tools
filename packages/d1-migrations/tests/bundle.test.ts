import { readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { describe, expect, it } from "vitest";
import { bundleD1Migrations, readD1Migrations } from "../src/bundle.js";
import { FIXTURES, loadWrangler, project, temporaryDirectory } from "./helpers.js";

loadWrangler();

describe("readD1Migrations", () => {
  // These pin what Wrangler's splitter gives for the cases a hand-written splitter gets wrong. When
  // a Wrangler upgrade changes one, this fails before any database sees the difference.
  it("splits statements as Wrangler does: comments, strings, triggers and views", async () => {
    const migrations = await readD1Migrations({ cwd: path.join(FIXTURES, "flat") });
    expect(migrations.map((migration) => migration.name)).toEqual([
      "0001_init.sql",
      "0002_triggers.sql",
      "0003_seed.sql",
    ]);
    expect(migrations[0]!.queries).toEqual([
      "-- Customers; a comment with a semicolon; in it.\nCREATE TABLE customers (\n  id INTEGER PRIMARY KEY,\n  name TEXT NOT NULL,\n  note TEXT DEFAULT 'it''s; fine' -- a quote and a semicolon in a string\n)",
      "/* A block comment; with a semicolon,\n   over two lines. */\nCREATE TABLE orders (\n  id INTEGER PRIMARY KEY,\n  customer_id INTEGER NOT NULL REFERENCES customers (id),\n  status TEXT NOT NULL DEFAULT 'new',\n  total INTEGER NOT NULL DEFAULT 0\n)",
      "CREATE INDEX orders_by_customer ON orders (customer_id)",
    ]);
    expect(migrations[1]!.queries).toEqual([
      "CREATE TABLE order_log (\n  order_id INTEGER NOT NULL,\n  message TEXT NOT NULL\n)",
      "CREATE TRIGGER orders_log_status AFTER UPDATE OF status ON orders\nBEGIN\n  INSERT INTO order_log (order_id, message)\n  VALUES (NEW.id, CASE NEW.status WHEN 'paid' THEN 'paid; thanks' ELSE 'now ' || NEW.status END);\n  UPDATE orders SET total = total WHERE id = NEW.id;\nEND",
      "CREATE VIEW open_orders AS SELECT * FROM orders WHERE status <> 'done'",
    ]);
    // The comment after the last statement goes with the INSERT Wrangler adds, and so is dropped.
    expect(migrations[2]!.queries).toEqual([
      "INSERT INTO customers (id, name) VALUES (1, 'Ada; Lovelace'), (2, '\"Grace\" Hopper')",
      "INSERT INTO orders (id, customer_id, status) VALUES (1, 1, 'new')",
      "UPDATE orders SET status = 'paid' WHERE id = 1",
    ]);
  });

  it("reads a migration with one statement, or none", async () => {
    const dir = project("order", {}, []);
    writeFileSync(path.join(dir, "migrations", "0001_one.sql"), "CREATE TABLE one (id INTEGER);\n");
    writeFileSync(path.join(dir, "migrations", "0002_none.sql"), "-- Nothing to do yet.\n");
    writeFileSync(path.join(dir, "migrations", "0003_empty.sql"), "");
    expect(await readD1Migrations({ cwd: dir })).toEqual([
      { name: "0001_one.sql", queries: ["CREATE TABLE one (id INTEGER)"] },
      { name: "0002_none.sql", queries: [] },
      { name: "0003_empty.sql", queries: [] },
    ]);
  });

  it("refuses a migration whose last statement Wrangler would run together with its INSERT", async () => {
    const dir = project("order", {}, []);
    writeFileSync(
      path.join(dir, "migrations", "0001_open.sql"),
      "CREATE TABLE a (id INTEGER);\nCREATE TABLE b (id INTEGER)\n",
    );
    await expect(readD1Migrations({ cwd: dir })).rejects.toThrow(
      "Migration 0001_open.sql does not end with a complete statement",
    );
  });

  it("splits Drizzle's layout, statement-breakpoint comments and all", async () => {
    const migrations = await readD1Migrations({
      cwd: path.join(FIXTURES, "drizzle"),
      dir: "drizzle",
      pattern: "drizzle/*/migration.sql",
      table: "schema_migrations",
    });
    expect(migrations.map((migration) => [migration.name, migration.queries.length])).toEqual([
      ["0000_init/migration.sql", 2],
      ["0001_posts/migration.sql", 1],
    ]);
  });
});

describe("bundleD1Migrations", () => {
  it("writes a JavaScript module that exports the migrations and their table", async () => {
    const dir = temporaryDirectory();
    const result = await bundleD1Migrations({
      cwd: path.join(FIXTURES, "order"),
      out: path.join(dir, "generated", "migrations.js"),
      table: "schema_migrations",
    });
    expect(result).toMatchObject({ table: "schema_migrations", changed: true });
    expect(result.out).toBe(path.join(dir, "generated", "migrations.js"));

    const source = readFileSync(result.out, "utf8");
    expect(source).toContain("// Generated by @rivi-software/d1-migrations from migrations/.");
    expect(source).toContain('/** @type {import("@rivi-software/d1-migrations").D1Migration[]} */');
    const module = await import(pathToFileURL(result.out).href);
    expect(module.table).toBe("schema_migrations");
    expect(module.migrations).toEqual(result.migrations);
    expect(module.default).toEqual({ table: "schema_migrations", migrations: result.migrations });
    expect(module.migrations[0]).toEqual({
      name: "1_one.sql",
      queries: ["CREATE TABLE one (id INTEGER)"],
    });
  });

  it("writes TypeScript for a .ts file", async () => {
    const dir = temporaryDirectory();
    const { out } = await bundleD1Migrations({
      cwd: path.join(FIXTURES, "flat"),
      out: path.join(dir, "migrations.ts"),
    });
    const source = readFileSync(out, "utf8");
    expect(source).toContain('import type { D1Migration } from "@rivi-software/d1-migrations";');
    expect(source).toContain('export const table = "d1_migrations";');
    expect(source).toContain(
      'export const migrations: D1Migration[] = [\n  {\n    name: "0001_init.sql",',
    );
    expect(source.endsWith("export default { table, migrations };\n")).toBe(true);
  });

  it("leaves an unchanged module alone", async () => {
    const dir = temporaryDirectory();
    const options = { cwd: path.join(FIXTURES, "flat"), out: path.join(dir, "migrations.js") };
    await bundleD1Migrations(options);
    const written = statSync(options.out).mtimeMs;
    const again = await bundleD1Migrations(options);
    expect(again.changed).toBe(false);
    expect(statSync(options.out).mtimeMs).toBe(written);
  });

  it("writes an empty list when there are no migrations yet", async () => {
    const dir = project("order", {}, []);
    const { out } = await bundleD1Migrations({ cwd: dir, out: "migrations.js" });
    expect(out).toBe(path.join(dir, "migrations.js"));
    const module = await import(pathToFileURL(out).href);
    expect(module.default).toEqual({ table: "d1_migrations", migrations: [] });
  });
});
